"""C# emitter: renders the `Api` IR (see `codegen/ir.py`) into a complete, typed, async
GetResponse.Api client — models, per-tag resource clients, the root client, the shared HTTP
pipeline, and an xUnit test project — under `get-response-cs/`.

Regenerate via `python -m codegen.generate --csharp`. Two buckets:

- **Always generated** (wiped + rewritten every run, never hand-edit): `GetResponse.Api/Models/`
  (+ `Models/Enums/`), `GetResponse.Api/Resources/`, and `GetResponse.Api/GetResponseClient.Resources.cs`
  (the generated half of the `GetResponseClient` partial class -- one property + one
  `InitializeResourceGroups` assignment per resource tag).
- **Scaffold-once** (written only if missing, then permanently hand-maintained): everything
  else -- `GetResponse.sln`, both `.csproj` files, `.editorconfig`, `GetResponse.Api/README.md`,
  the hand-written half of `GetResponseClient.cs`, `GetResponseClientOptions.cs`,
  `GetResponseApiException.cs`, `RateLimitOptions.cs`, `RateLimitException.cs`, `Pagination.cs`,
  `Internal/ApiHttp.cs`, `Internal/RateLimiter.cs`, `Internal/EnumWireValues.cs`, and the whole
  `GetResponse.Api.Tests/` project. `.sln` and both `.csproj` files are scaffolded via the real
  `dotnet` CLI (`dotnet new sln`/`classlib`/`xunit`, `dotnet sln add`, `dotnet add
  package`/`reference`) the one time they're created, then hand-patched for the properties no
  CLI flag can set (multi-targeting, NuGet package metadata). `get-response-cs/nuget.config` is
  already scaffold-only today, created outside `emit()` -- left alone here too.

A new resource tag in the spec still needs no hand-edit: `GetResponseClient` is a `partial
class` split across the always-generated `GetResponseClient.Resources.cs` (properties +
`InitializeResourceGroups`) and the scaffold-once `GetResponseClient.cs` (constants,
`JsonOptions`, constructors, `Dispose`), with each constructor calling
`InitializeResourceGroups(pipeline)` after building the pipeline.
"""

