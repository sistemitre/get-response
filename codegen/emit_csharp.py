# -- emit orchestration -----------------------------------------------------------------------


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def _write_once(path: Path, content: str) -> None:
    """Like `_write`, but a no-op if the file already exists -- for scaffold-bucket files that
    become hand-maintained after first creation (see module docstring)."""
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def emit(api: Api, out_dir: str = "get-response-cs") -> None:
    """Generate the complete C# GetResponse.Api solution (client, models, tests) into `out_dir`.

    Two buckets (see module docstring): `Models/`, `Resources/`, and
    `GetResponseClient.Resources.cs` are spec-derived and fully rewritten every run; everything
    else is scaffolded once (written only if missing) and then hand-maintained.
    """
    root = Path(out_dir)
    api_dir = root / "GetResponse.Api"
    models_dir = api_dir / "Models"
    enums_dir = models_dir / "Enums"
    resources_dir = api_dir / "Resources"
    internal_dir = api_dir / "Internal"
    tests_dir = root / "GetResponse.Api.Tests"
    api_csproj = api_dir / "GetResponse.Api.csproj"
    tests_csproj = tests_dir / "GetResponse.Api.Tests.csproj"
    sln_path = root / "GetResponse.sln"

    # -- always generated: narrow wipe of only the spec-derived subtrees, never the whole
    # project (that would also destroy scaffold-once hand-maintained files) --
    for stale in (models_dir, resources_dir):
        if stale.exists():
            shutil.rmtree(stale)
    (api_dir / "GetResponseClient.Resources.cs").unlink(missing_ok=True)

    _write_types_grouped(
        models_dir,
        [m.name for m in api.models],
        {m.name: _model_body_lines(m) for m in api.models},
        _MODEL_FILE_USINGS,
    )
    _write_types_grouped(
        enums_dir,
        [e.name for e in api.enums],
        {e.name: _enum_body_lines(e) for e in api.enums},
        _ENUM_FILE_USINGS,
    )

    resource_groups = _group_operations_by_tag(api.operations)
    for tag, ops in resource_groups.items():
        class_name = f"{_tag_identifier(tag)}Client"
        _write(resources_dir / f"{class_name}.cs", _render_resource_client(tag, ops))

    _write(api_dir / "GetResponseClient.Resources.cs", _render_client_resources_cs(resource_groups))

    # -- scaffold-once: hand-maintained core runtime, project files, and tests --
    _write_once(api_dir / "GetResponseClient.cs", _CLIENT_CS)
    _write_once(api_dir / "GetResponseClientOptions.cs", _CLIENT_OPTIONS_CS)
    _write_once(api_dir / "GetResponseApiException.cs", _API_EXCEPTION_CS)
    _write_once(api_dir / "RateLimitOptions.cs", _RATE_LIMIT_OPTIONS_CS)
    _write_once(api_dir / "RateLimitException.cs", _RATE_LIMIT_EXCEPTION_CS)
    _write_once(api_dir / "Pagination.cs", _PAGINATION_CS)
    _write_once(internal_dir / "ApiHttp.cs", _API_HTTP_CS)
    _write_once(internal_dir / "RateLimiter.cs", _RATE_LIMITER_CS)
    _write_once(internal_dir / "EnumWireValues.cs", _ENUM_WIRE_VALUES_CS)
    _write_once(api_dir / "README.md", _API_README_MD)
    _write_once(root / ".editorconfig", _EDITORCONFIG)

    _write_once(tests_dir / "StubHttpMessageHandler.cs", _STUB_HANDLER_CS)
    _write_once(tests_dir / "AuthHeaderTests.cs", _render_auth_tests())
    _write_once(tests_dir / "QueryBuildingTests.cs", _render_query_building_tests())
    _write_once(tests_dir / "ModelSerializationTests.cs", _render_model_serialization_tests())
    _write_once(tests_dir / "PaginationTests.cs", _render_pagination_tests())
    _write_once(tests_dir / "ErrorMappingTests.cs", _render_error_mapping_tests())
    _write_once(tests_dir / "RateLimitingTests.cs", _render_rate_limiting_tests())

    print(f"C# emit complete: {len(api.models)} models, {len(api.enums)} enums, "
          f"{len(resource_groups)} resource clients, {len(api.operations)} operations.")

    # -- .sln / .csproj scaffolding: real `dotnet` CLI, gated to run only once (see
    # _scaffold_solution_and_projects) --
    stale_slnx = root / "GetResponse.slnx"
    if stale_slnx.exists():
        stale_slnx.unlink()
    _scaffold_solution_and_projects(root, api_dir, tests_dir, api_csproj, tests_csproj, sln_path)

    # -- normalize whitespace/style so `dotnet format --verify-no-changes` is a no-op --
    _run(["dotnet", "format", str(sln_path)], check=False)


def _run(cmd: list[str], check: bool = True) -> None:
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"$ {' '.join(cmd)}\n{result.stdout}\n{result.stderr}")
        if check:
            raise RuntimeError(f"Command failed: {' '.join(cmd)}")
